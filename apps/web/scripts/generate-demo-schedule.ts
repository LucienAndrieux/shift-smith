import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { generateDemoSchedule } from "@/lib/domain/demo-schedule";
import {
  buildSeedPlan,
  seedPlanToScheduleInput,
} from "@/lib/domain/seed-mapping";
import { summarizeViolations, validateSchedule } from "@/lib/domain/validator";
import { findRepoRoot } from "./load-env";

/**
 * Generates the demo reference schedule (first demo month, see
 * src/lib/domain/demo-schedule.ts) and writes it into docs/seed-data.json under
 * `reference_schedule`.
 */

const seedPath = path.join(findRepoRoot(), "docs", "seed-data.json");
const raw = JSON.parse(readFileSync(seedPath, "utf8"));
delete raw.reference_schedule;
const demo = generateDemoSchedule(buildSeedPlan(raw));
const label = `${demo.year}-${String(demo.month).padStart(2, "0")}`;

const errors = demo.cleanViolations.filter((v) => v.severity === "error");
console.log(
  `Generated ${label}: ${errors.length} error(s), ${
    demo.cleanViolations.length - errors.length
  } warning(s) before the deliberate mistakes.`,
);
for (const v of demo.cleanViolations)
  console.log(`  [${v.severity}] ${v.message}`);
console.log("Deliberate mistakes:");
for (const m of demo.mistakes) console.log(`  • ${m}`);

raw.reference_schedule = {
  month: label,
  note: `Generated by scripts/generate-demo-schedule.ts. Deliberate mistakes: ${demo.mistakes.join("; ")}.`,
  grids: demo.grids,
};
const final = validateSchedule(seedPlanToScheduleInput(buildSeedPlan(raw)));
console.table(
  summarizeViolations(final.violations).map((s) => ({
    rule: s.label,
    errors: s.error,
    warnings: s.warning,
  })),
);
writeFileSync(seedPath, `${JSON.stringify(raw, null, 2)}\n`);
console.log(`Written to ${path.relative(findRepoRoot(), seedPath)}`);
